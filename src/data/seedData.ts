// Helper to generate route waypoints between 2 coords
export function generateRoutePoints(start: { lat: number; lng: number }, end: { lat: number; lng: number }, steps = 18): [number, number][] {
  const points: [number, number][] = [];
  const midLat = (start.lat + end.lat) / 2 + (Math.sin((start.lat + end.lng) * 10) * 0.004);
  const midLng = (start.lng + end.lng) / 2 + (Math.cos((start.lng + end.lat) * 10) * 0.004);

  for (let i = 0; i <= steps; i++) {
    const t = i / steps;
    // Quadratic bezier curve for realistic street curves
    const lat = (1 - t) * (1 - t) * start.lat + 2 * (1 - t) * t * midLat + t * t * end.lat;
    const lng = (1 - t) * (1 - t) * start.lng + 2 * (1 - t) * t * midLng + t * t * end.lng;
    points.push([lat, lng]);
  }
  return points;
}

